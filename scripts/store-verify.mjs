/**
 * The parts of `pnpm store:verify` that can be reasoned about without a
 * network: where the ZIP starts inside a CRX, what a tree comparison means,
 * and how the command line is read.
 *
 * Why this exists at all: the store's public page reports a *version*, and a
 * version is not the bytes. v2.2.0 was recorded in the ledger as uploaded
 * before the HUD security fix was built, and the page still said "2.2.0" —
 * the version matched, the bytes did not. Checking the public page is not a
 * release check; checking the live CRX's files against the package is.
 */

import { createHash } from 'node:crypto';

/**
 * The listing this repository publishes to. It is public (it is in the store
 * URL and in `docs/store-release-log.md`), so it is not a secret and does not
 * need the credentials file; `--item` overrides it for a fork.
 */
export const DEFAULT_ITEM_ID = 'llicfmiagjiknidigpdcnogfeheogpfd';

/** Chrome's update service answers with this prefix when it found an item. */
const CRX_MAGIC = 'Cr24';

/**
 * Store-added files. `_metadata/verified_contents.json` is generated by the
 * store when it signs the CRX; it is not part of the uploaded ZIP and its
 * hash can never match.
 */
const IGNORED_PREFIXES = ['_metadata/'];

export class StoreVerifyError extends Error {}

/** Read the command line. */
export function parseArgs(argv) {
  const options = {
    zip: null,
    itemId: DEFAULT_ITEM_ID,
    json: false,
    help: false,
  };

  for (const arg of argv) {
    if (arg === '--help' || arg === '-h') {
      options.help = true;
    } else if (arg === '--json') {
      options.json = true;
    } else if (arg.startsWith('--item=')) {
      const value = arg.slice('--item='.length).trim();
      if (!value) {
        throw new StoreVerifyError('--item needs an item id');
      }
      options.itemId = value;
    } else if (arg.startsWith('--')) {
      throw new StoreVerifyError(`unknown flag: ${arg}`);
    } else if (options.zip === null) {
      options.zip = arg;
    } else {
      throw new StoreVerifyError(`unexpected argument: ${arg}`);
    }
  }

  return options;
}

/**
 * Find the ZIP inside a CRX3 (or legacy CRX2) container.
 *
 * The store serves `application/x-chrome-extension`, not a ZIP: a CRX is a
 * short header followed by the ZIP that was uploaded. Slicing at the wrong
 * offset produces an archive that unzip rejects with a message that says
 * nothing about the header, so the offset is computed from the declared
 * header length rather than searched for.
 */
export function crxZipOffset(bytes) {
  if (bytes.length < 16 || bytes.toString('latin1', 0, 4) !== CRX_MAGIC) {
    throw new StoreVerifyError('not a CRX: missing the Cr24 header');
  }

  const version = bytes.readUInt32LE(4);
  let offset;

  if (version === 3) {
    const headerSize = bytes.readUInt32LE(8);
    offset = 12 + headerSize;
  } else if (version === 2) {
    const publicKeySize = bytes.readUInt32LE(8);
    const signatureSize = bytes.readUInt32LE(12);
    offset = 16 + publicKeySize + signatureSize;
  } else {
    throw new StoreVerifyError(`unsupported CRX version: ${version}`);
  }

  if (
    offset + 4 > bytes.length ||
    bytes.toString('latin1', offset, offset + 4) !== 'PK\x03\x04'
  ) {
    throw new StoreVerifyError(
      `CRX header says the ZIP starts at ${offset}, but it does not`
    );
  }

  return offset;
}

/** Hash one file's bytes the way the release checksum does. */
export function hashBytes(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

/**
 * Rewrite `manifest.json` bytes so the two trees are comparable.
 *
 * The store injects `update_url` into the manifest when it signs the CRX —
 * an uploaded ZIP does not carry the key. Dropping it from both sides makes
 * "store rewrote one key" distinct from "the uploaded package changed"; any
 * other manifest edit still shows up as a hash difference.
 */
export function normaliseManifest(bytes) {
  try {
    const manifest = JSON.parse(bytes.toString('utf8'));
    if (manifest === null || typeof manifest !== 'object') {
      return bytes;
    }
    delete manifest.update_url;
    return Buffer.from(JSON.stringify(manifest), 'utf8');
  } catch {
    // A manifest that does not parse is compared verbatim and fails below.
    return bytes;
  }
}

/**
 * Turn `{ path: bytes }` into `{ path: sha256 }`, dropping store metadata.
 *
 * Paths are POSIX and relative to the archive root, because that is how both
 * a ZIP listing and the ledger name files.
 */
export function hashTree(files) {
  const out = new Map();
  for (const [filePath, bytes] of Object.entries(files)) {
    const normalised = filePath.split('\\').join('/');
    if (IGNORED_PREFIXES.some(prefix => normalised.startsWith(prefix))) {
      continue;
    }
    const payload =
      normalised === 'manifest.json' ? normaliseManifest(bytes) : bytes;
    out.set(normalised, hashBytes(payload));
  }
  return out;
}

/**
 * Compare the expected package with the live bundle, file by file.
 *
 * `missing` is a file the package has and the store does not; `extra` is the
 * reverse. Both are failures: the store should serve exactly what was
 * uploaded (plus `_metadata/`, which is ignored).
 */
export function compareBundles(expected, live) {
  const missing = [];
  const extra = [];
  const changed = [];

  for (const [filePath, digest] of expected) {
    if (!live.has(filePath)) {
      missing.push(filePath);
    } else if (live.get(filePath) !== digest) {
      changed.push(filePath);
    }
  }
  for (const filePath of live.keys()) {
    if (!expected.has(filePath)) {
      extra.push(filePath);
    }
  }

  return {
    ok: missing.length === 0 && extra.length === 0 && changed.length === 0,
    missing: missing.sort(),
    extra: extra.sort(),
    changed: changed.sort(),
  };
}

/**
 * A one-block, pasteable verdict. The ledger quotes this, not a rewrite of
 * it, so the evidence and the record cannot drift apart.
 */
export function describeVerdict({ expectedVersion, liveVersion, result }) {
  const lines = [
    `expected version : ${expectedVersion}`,
    `live version     : ${liveVersion ?? 'unknown'}`,
    `files differing  : ${result.changed.length}`,
    `files missing    : ${result.missing.length}`,
    `files extra      : ${result.extra.length}`,
  ];

  if (result.changed.length > 0) {
    lines.push(`changed          : ${result.changed.join(', ')}`);
  }
  if (result.missing.length > 0) {
    lines.push(`missing          : ${result.missing.join(', ')}`);
  }
  if (result.extra.length > 0) {
    lines.push(`extra            : ${result.extra.join(', ')}`);
  }

  lines.push(
    result.ok && expectedVersion === liveVersion
      ? 'verdict          : OK — the live CRX is the package'
      : 'verdict          : MISMATCH — the live CRX is not the package'
  );

  return lines.join('\n');
}
