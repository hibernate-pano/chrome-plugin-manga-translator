/**
 * 一个内容脚本实例的运行标识。
 *
 * 每个内容脚本上下文（每个标签页、每个 frame）各自加载本模块一次，于是这个
 * id 在这一页的整个生命周期里都是同一个值。它要解决的问题是**取消**：
 *
 * 读者在某一页点了「取消当前翻译」，worker 队列里排着的请求必须停下来 ——
 * 它们每一个都会变成一次真实的、计费的请求。但队列是**所有标签页共用**的，
 * 所以不能把队列清空：读者在 A 页取消，不该把 B 页正在翻的章节一起扔掉。
 *
 * 队列按 `pageKey`（一张图）去重，没法回答"哪些工作是这一页的"。这个 id
 * 就是那个答案：每一个请求都带着它，取消时只丢带着同一个 id 的那些。
 *
 * 它必须由内容脚本持有，而不是由翻译服务持有：翻译服务在设置变化时会被重建
 * （`ensureServicesInitialized`），而"这一轮"不会因为设置变了就变成另一轮。
 */
export const RUN_SCOPE_ID = `run-${Math.random().toString(36).slice(2, 10)}`;
